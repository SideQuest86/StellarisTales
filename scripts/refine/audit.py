"""Full-catalogue refinement audit (2026-10): per category, how many stories were covered by the placeholder review,
how many reviewed wording entries apply, open reviewer issues, and automated checks over every compiled story:
placeholders still on generic fallback wording, unresolved $KEY$ references, guides with raw HTML or missing.
Writes docs/refine/AUDIT.md. Run after merge_placeholders.py and compile-stories.py."""
import collections, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
P = re.compile(r'\[([^\[\]]+)\]')
REF = re.compile(r'\$([A-Za-z_][\w.]*)\$')
index = json.loads((ROOT / 'public/stories/index.json').read_text(encoding='utf-8'))['stories']
scripted = set(json.loads((ROOT / 'public/stories/names.json').read_text(encoding='utf-8')))
groups = json.loads((ROOT / 'docs/refine/placeholders/groups.json').read_text(encoding='utf-8'))['groups']
owner = {sid: g['id'] for g in groups for sid in g['stories']}
outs = {}
rendered = {}
# Latest review per story wins: rendered- (first), rendered2- (independent second), rendered3- (residual).
for pattern in ('rendered-*.json', 'rendered2-*.json', 'rendered3-*.json', 'rendered4-*.json'):
    for f in sorted((ROOT / 'docs/refine/placeholders/out').glob(pattern)):
        if f.name == 'rendered-specimens.json':
            continue
        rendered.update({k: v for k, v in json.loads(f.read_text(encoding='utf-8')).items() if (v or {}).get('reviewed')})
for g in groups:
    f = ROOT / 'docs/refine/placeholders/out' / f"{g['id']}.json"
    outs.update(json.loads(f.read_text(encoding='utf-8')) if f.exists() else {})
row = collections.defaultdict(collections.Counter)
fallback_examples, ref_examples = [], collections.Counter()
for s in index:
    sid, cat = s['id'], s['category']
    r = row[cat]
    r['stories'] += 1
    d = json.loads((ROOT / 'public/stories' / f'{sid}.json').read_text(encoding='utf-8'))
    frag_path = ROOT / 'content/stories' / f'{sid}.json'
    frag = json.loads(frag_path.read_text(encoding='utf-8-sig')) if frag_path.exists() else {}
    if sid in owner:
        r['with placeholders'] += 1
        r['reviewed'] += sid in outs
        r['rendered confirmed'] += sid in rendered
        r['game-text exceptions'] += len([e for e in (rendered.get(sid) or {}).get('exceptions') or [] if not re.search(r'proper name|personal name|unit name|by the name of|needs a name', e, re.I)])
    r['reviewed entries'] += len(frag.get('placeholders', {})) + sum(len(v) for v in frag.get('placeholderDocs', {}).values())
    for c in d['chapters']:
        for key, w in (c.get('names') or {}).items():
            if w.get('default') and key.split('|')[0].split('.')[-1] not in scripted:
                r['generic fallback keys'] += 1
                if len(fallback_examples) < 40:
                    fallback_examples.append(f'{sid} · {c["id"]} · `{key}`')
    text = json.dumps(d['chapters'], ensure_ascii=False)
    refs = REF.findall(text)
    r['$refs undefined in game (omitted)'] += len(refs)
    ref_examples.update(refs)
    summary = (d.get('summary') or {}).get('text')
    if not summary:
        r['no guide'] += 1
    elif re.search(r'<\s*(script|iframe|img|div|span)\b', summary, re.I):
        r['guide raw HTML'] += 1
cols = ['stories', 'with placeholders', 'reviewed', 'rendered confirmed', 'reviewed entries', 'game-text exceptions', 'generic fallback keys',
        '$refs undefined in game (omitted)', 'no guide', 'guide raw HTML']
lines = ['# Refinement audit — full catalogue (generated by scripts/refine/audit.py)', '',
         'Every story was processed; "reviewed" counts stories whose placeholders a reviewer read in complete sentences '
         '(docs/refine/placeholders/out/). Rendered confirmed = a reviewer then read every rendered sentence of the story '
         'as the site shows it (docs/refine/placeholders/rendered/). Game-text exceptions are sentences that cannot read '
         'naturally without rewriting the game\'s own text (LEDGER.md); exceptions about empty phrases were fixed in the '
         'renderer after the review (0 empty phrases remain). Generic fallback keys are '
         'placeholders still shown with the neutral default because the reviewer kept it or the key was not listed.', '',
         '| Category | ' + ' | '.join(cols) + ' |', '| --- |' + ' ---: |' * len(cols)]
total = collections.Counter()
for cat in sorted(row):
    total.update(row[cat])
    lines.append(f'| {cat} | ' + ' | '.join(str(row[cat][c]) for c in cols) + ' |')
lines.append('| **all** | ' + ' | '.join(f'**{total[c]}**' for c in cols) + ' |')
lines += ['', '## $KEY$ references not defined in the game''s own localisation (the reader omits them; progress counters $COUNT$/$REQUIRED$ read as \"the required number of\")', '',
          ', '.join(f'`{k}` ×{n}' for k, n in ref_examples.most_common(25)) or 'none', '',
          '## Generic fallback examples', ''] + [f'- {e}' for e in fallback_examples]
(ROOT / 'docs/refine/AUDIT.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(dict(total))
