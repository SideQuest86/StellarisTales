def strongly_connected(nodes, adj):
    """Iterative Tarjan; returns {node: component index}."""
    index, low, comp, stack, on_stack = {}, {}, {}, [], set()
    counter = [0, 0]
    for start in nodes:
        if start in index:
            continue
        work = [(start, iter(adj.get(start, ())))]
        index[start] = low[start] = counter[0]
        counter[0] += 1
        stack.append(start)
        on_stack.add(start)
        while work:
            node, it = work[-1]
            advanced = False
            for nxt in it:
                if nxt not in index:
                    index[nxt] = low[nxt] = counter[0]
                    counter[0] += 1
                    stack.append(nxt)
                    on_stack.add(nxt)
                    work.append((nxt, iter(adj.get(nxt, ()))))
                    advanced = True
                    break
                if nxt in on_stack:
                    low[node] = min(low[node], index[nxt])
            if advanced:
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[node])
            if low[node] == index[node]:
                while True:
                    member = stack.pop()
                    on_stack.discard(member)
                    comp[member] = counter[1]
                    if member == node:
                        break
                counter[1] += 1
    return comp


class Compiler:
    def __init__(self):
        rawindex = read(ROOT / 'public/data/index.json')
        self.version = rawindex['version']
        self.meta = {m['id']: m for m in rawindex['records']}
        self.records = [r for g in rawindex['groups'] for r in read(ROOT / 'public/data/groups' / f"{g['id']}.json")]
        self.graph = read(ROOT / 'public/data/source-graph.json')
        self.loc = read(ROOT / 'public/data/script-loc.json')
        labels = read(ROOT / 'public/data/reaction-labels.json')
        self.cond = Conditions(labels, lambda key: self.loc.get(key) if any(self.loc.get(key, {}).values()) else None)
        self.fragments = {}
        for path in sorted((ROOT / 'content/stories').glob('*.json')):
            fragment = read(path)
            if fragment.get('id', path.stem) != path.stem:
                raise ValueError(f'Story fragment id must match its file name: {path.name}')
            self.fragments[path.stem] = fragment
        chron = ROOT / 'content/chronology'
        self.hub_review = read(chron / 'hubs.json')
        # Reviewed facts live in one fragment per story; keyed facts should be unique across fragments.
        self.duplicate_facts = []
        self.bridges, self.suppressed = [], collections.defaultdict(list)
        self.dialogues, self.readings, self.endings, self.notes = {}, {}, {}, collections.defaultdict(list)
        self.node_labels, self.openings, self.unreachable = {}, {}, {}
        self.no_stage_sequence = set()
        for sid, fragment in self.fragments.items():
            self.bridges += [{**b, 'fragment': sid} for b in fragment.get('bridges', [])]
            for s in fragment.get('suppress', []):
                self.suppressed[s['from']].append(s)
            for field, target in (('dialogues', self.dialogues), ('readings', self.readings), ('endings', self.endings)):
                for key, value in fragment.get(field, {}).items():
                    if key in target:
                        if target[key] != value:  # two reviewers described the same doc; keep the first, report
                            self.duplicate_facts.append(f'{sid}: {field} for {key} also reviewed in another fragment')
                        continue
                    target[key] = value
            self.no_stage_sequence.update(fragment.get('noStageSequence', []))
            for doc, note in fragment.get('unreachable', {}).items():
                self.unreachable[doc] = {k: note[k] for k in ('zh', 'en') if k in note}
            for note in fragment.get('notes', []):
                self.notes[note['doc']].append({k: note[k] for k in ('zh', 'en', 'kind') if k in note})
            if fragment.get('nodeLabels'):
                self.node_labels[sid] = fragment['nodeLabels']
            if fragment.get('opening'):
                self.openings[sid] = fragment['opening']
            self.hub_review['hubs'] = self.hub_review['hubs'] + fragment.get('hubs', [])
            self.hub_review['notHubs'] = self.hub_review.get('notHubs', []) + fragment.get('notHubs', [])
        self.report = collections.Counter()
        self.composite_cache = {}
        self.container_of = {}
        self.hook_cache = {}
        self.excluded = collections.defaultdict(set)
        self.warnings = list(self.duplicate_facts)
        self.defined = read(ROOT / 'public/data/scripted-loc.json')
        self.used_names = set()

    # ------------------------------------------------------------------ records ---
    def prepare(self):
        origin_config, self.origin_evidence = build_origin_families(ROOT, self.records)
        for f in origin_config:
            o = f['origin']
            rid = 'origin-intro:' + o['id']
            f['members'].append(rid)
            f['start'] = rid
            self.records.append({'id': rid, 'eventId': o['id'], 'kind': 'origin_intro', 'source': o['source'],
                                 'group': 'origin-introductions', 'script': '', 'trigger': '', 'titles': [o['title']],
                                 'descriptions': [o['description']], 'sections': o['introductions'],
                                 'picture': o['picture'], 'hidden': False, 'options': [], 'links': [], 'line': 0})
            self.meta[rid] = {'hasText': True, 'category': 'origins', 'hidden': False}
        self.byid = {r['id']: r for r in self.records}
        self.order = {r['id']: i for i, r in enumerate(self.records)}
        self.families = read(ROOT / 'content/story-families.json') + origin_config
        for sid, fragment in self.fragments.items():
            if 'family' in fragment:  # a reviewed fragment family replaces a legacy family of the same id
                self.families = [f for f in self.families if f['id'] != sid] + [{**fragment['family'], 'id': sid}]
        self.origin_ids = {f['id'] for f in origin_config}

    def kind(self, rid):
        return DOC_KIND.get(self.byid[rid]['kind'], 'event')

    def readable(self, rid):
        r = self.byid[rid]
        if any(s in r['source'] for s in NON_STORY_SOURCES):
            return False
        if 'is_test_event = yes' in r.get('trigger', '') or re.search(r'\bis_test_event\s*=\s*yes', r.get('script', '')[:400]):
            return False  # developer test events (never fire in a normal game)
        if rid in ('event_chains:test_chain', 'event_chains:test_chain_2'):
            return False  # developer test chains: no shipped script begins them (review of chain-test-chain, 2026-10-13)
        return bool(self.meta.get(rid, {}).get('hasText')) and not r['hidden']

    # -------------------------------------------------------------------- edges ---
    def build_edges(self):
        self.out = collections.defaultdict(list)
        self.triggers = collections.defaultdict(list)
        callers = collections.defaultdict(set)
        caller_files = collections.defaultdict(set)
        for c in self.graph['calls']:
            if c['via'] == 'scripted_effect' or c['to'] not in self.byid or c['from'] == c['to']:
                continue
            if c['from'] in self.byid:
                # Spawning an anomaly starts that anomaly's own story: trigger information, never a continuation.
                if c['via'] == 'add_anomaly' or any(s in self.byid[c['from']]['source'] for s in NON_STORY_SOURCES):
                    self.triggers[c['to']].append(c)
                    continue
                self.out[c['from']].append(c)
                callers[c['to']].add(c['from'])
                caller_files[c['to']].add(self.byid[c['from']]['source'])
            else:
                self.triggers[c['to']].append(c)
        # Reviewed hidden dispatchers (e.g. game_start.1) behave like on_actions: they fan out to unrelated
        # content, so each target starts its own story instead of one catch-all.
        for src in self.hub_review.get('dispatchers', []):
            if src in self.out:
                for c in self.out.pop(src):
                    self.triggers[c['to']].append(c)
                    callers[c['to']].discard(src)
                self.report['dispatchers'] += 1
        self.callers = callers
        # Shared helpers (e.g. the generic contact reports, archaeology dig incidents) are not part of their callers.
        self.hubs = {t for t, s in callers.items() if (len(s) >= 10 and len(caller_files[t]) >= 3) or len(s) >= 25}
        self.hubs |= {h for h in self.hub_review['hubs'] if h in self.byid}
        self.hubs -= set(self.hub_review.get('notHubs', []))
        self.report['hubs'] = len(self.hubs)

    def composite(self, src):
        """Outgoing edges of `src` to readable docs, folding hidden routers into the edge context."""
        if src in self.composite_cache:
            return self.composite_cache[src]
        results = []

        def go(node, segments, seen, depth):
            for call in self.out.get(node, []):
                target = call['to']
                if target in seen or len(results) > 400:
                    continue
                if target in self.hubs and not self.readable(target):
                    self.report['hidden_hub_edges'] += 1
                    continue
                if self.readable(target) or target in self.hubs:
                    results.append((target, segments + [call]))
                elif depth < 10:
                    go(target, segments + [call], seen | {target}, depth + 1)
        go(src, [], {src}, 0)
        self.composite_cache[src] = results
        return results

    def reviewed_edges(self):
        """Reviewed bridges and origin openings are tree edges, keyed by their source doc."""
        extra = collections.defaultdict(list)
        for bridge in self.bridges:
            if bridge.get('annotate'):
                continue
            if bridge['from'] not in self.byid or bridge['to'] not in self.byid:
                self.report['bridge_missing_record'] += 1
                continue
            info = {'kind': 'bridge', 'label': bridge['label'], 'conditional': bridge.get('conditional', False),
                    'source': f"content/stories/{bridge.get('fragment')}.json"}
            if 'choice' in bridge:
                keys = [o['label'].get('key', '') for o in self.byid[bridge['from']]['options']]
                if bridge['choice'] not in keys:
                    raise ValueError('Missing reviewed choice ' + bridge['choice'])
                info['optionIndex'] = keys.index(bridge['choice'])
                info['option'] = bridge['choice']
            if 'requiresVisited' in bridge:
                info['requiresVisited'] = bridge['requiresVisited']
            if bridge.get('external'):  # a link into another story; never absorbs the target root
                info['external'] = True
            extra[bridge['from']].append((bridge['to'], info))
        self.openings_start = {'origin-intro:' + sid for sid in self.openings}
        for sid, opening in self.openings.items():
            start = 'origin-intro:' + sid
            for key in opening['targets']:
                if key not in self.byid:
                    raise ValueError(f'Missing origin opening {sid}: {key}')
                extra[start].append((key, {'kind': 'entry', 'label': opening.get('labels', {}).get(key, opening['label']),
                                           'conditional': True, 'source': f'content/stories/{sid}.json'}))
        return extra

