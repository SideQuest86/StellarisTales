"""V4 story compiler: root-anchored story trees (see docs/STORY-MODEL-V4.md).

Inputs (generated by scripts/extract.py from the read-only game install, plus reviewed configuration):
  public/data/index.json + groups/   narrative records (events and narrative definitions, incl. anomaly categories)
  public/data/source-graph.json      whole-game call graph with structural context
  public/data/script-loc.json        original wording of tooltips referenced in conditions
  content/story-families.json, content/origin-families.json, content/stories/*.json, content/chronology/*.json

Model:
  * A story is a tree rooted at the game's own entry point: a curated family (origin, precursor chain, crisis…) or an
    automatic root — a strongly connected component of the narrative call graph that nothing outside it calls
    (anomaly categories, archaeological sites, on_action/decision-triggered events, looping contact menus).
  * Hidden events are routers; their weights, conditions and delays are folded into the edge that passes them.
  * A doc reachable from several roots appears in each of those trees. Reaching another root, a shared hub or a member
    of another curated family is a cross-story link, never a merge.

Output: public/stories/<id>.json (docs + tree), public/stories/index.json, public/data/story-coverage.json.
"""
