def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def clean(s):
    text = re.sub(r'§.', '', s or '').strip()
    text = re.sub(r'^(?:警告[：:]|WARNING:)[^\n]*(?:\n+|$)', '', text, flags=re.I)
    return text.strip()


