def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def clean(s):
    text = re.sub(r'§.', '', s or '').strip()
    text = re.sub(r'^(?:警告[：:]|WARNING:)[^\n]*(?:\n+|$)', '', text, flags=re.I)
    return text.strip()


def bilingual(t):
    return {lang: clean(t.get(lang, '')) for lang in ('zh', 'en')}


def slug(text):
    return re.sub(r'-+', '-', re.sub(r'[^a-z0-9]+', '-', text.lower())).strip('-')


def strongly_connected(nodes, adj):
    """Iterative Tarjan; returns {node: component index}."""
    index, low, comp, stack, on_stack = {}, {}, {}, [], set()
    counter = [0, 0]
    for start in nodes:
        if start in index:
            continue
        work = [(start, iter(adj.get(start, ())))]
        index[start] = low[start] = counter[0]
        counter[0] += 1
        stack.append(start)
        on_stack.add(start)
        while work:
            node, it = work[-1]
            advanced = False
            for nxt in it:
                if nxt not in index:
                    index[nxt] = low[nxt] = counter[0]
                    counter[0] += 1
                    stack.append(nxt)
                    on_stack.add(nxt)
                    work.append((nxt, iter(adj.get(nxt, ()))))
                    advanced = True
                    break
                if nxt in on_stack:
                    low[node] = min(low[node], index[nxt])
            if advanced:
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[node])
            if low[node] == index[node]:
                while True:
                    member = stack.pop()
                    on_stack.discard(member)
                    comp[member] = counter[1]
                    if member == node:
                        break
                counter[1] += 1
    return comp


class Compiler:
    def __init__(self):
        rawindex = read(ROOT / 'public/data/index.json')
        self.version = rawindex['version']
        self.meta = {m['id']: m for m in rawindex['records']}
        self.records = [r for g in rawindex['groups'] for r in read(ROOT / 'public/data/groups' / f"{g['id']}.json")]
        self.graph = read(ROOT / 'public/data/source-graph.json')
        self.loc = read(ROOT / 'public/data/script-loc.json')
        labels = read(ROOT / 'public/data/reaction-labels.json')
        self.cond = Conditions(labels, lambda key: self.loc.get(key) if any(self.loc.get(key, {}).values()) else None)
        self.fragments = {}
        for path in sorted((ROOT / 'content/stories').glob('*.json')):
            fragment = read(path)
            if fragment.get('id', path.stem) != path.stem:
                raise ValueError(f'Story fragment id must match its file name: {path.name}')
            self.fragments[path.stem] = fragment
        chron = ROOT / 'content/chronology'
        self.hub_review = read(chron / 'hubs.json')
        # Reviewed facts live in one fragment per story; keyed facts must be unique across fragments.
        self.bridges, self.suppressed = [], collections.defaultdict(list)
        self.dialogues, self.readings, self.endings, self.notes = {}, {}, {}, collections.defaultdict(list)
        self.node_labels, self.openings = {}, {}
        for sid, fragment in self.fragments.items():
            self.bridges += [{**b, 'fragment': sid} for b in fragment.get('bridges', [])]
            for s in fragment.get('suppress', []):
                self.suppressed[s['from']].append(s)
            for field, target in (('dialogues', self.dialogues), ('readings', self.readings), ('endings', self.endings)):
                for key, value in fragment.get(field, {}).items():
                    if key in target:
                        raise ValueError(f'{sid}: {field} for {key} is already reviewed in another fragment')
                    target[key] = value
            for note in fragment.get('notes', []):
                self.notes[note['doc']].append({k: note[k] for k in ('zh', 'en', 'kind') if k in note})
            if fragment.get('nodeLabels'):
                self.node_labels[sid] = fragment['nodeLabels']
            if fragment.get('opening'):
                self.openings[sid] = fragment['opening']
            self.hub_review['hubs'] = self.hub_review['hubs'] + fragment.get('hubs', [])
            self.hub_review['notHubs'] = self.hub_review.get('notHubs', []) + fragment.get('notHubs', [])
        self.report = collections.Counter()
        self.composite_cache = {}
        self.container_of = {}

    # ------------------------------------------------------------------ records ---
    def prepare(self):
        origin_config, self.origin_evidence = build_origin_families(ROOT, self.records)
        for f in origin_config:
            o = f['origin']
            rid = 'origin-intro:' + o['id']
            f['members'].append(rid)
            f['start'] = rid
            self.records.append({'id': rid, 'eventId': o['id'], 'kind': 'origin_intro', 'source': o['source'],
                                 'group': 'origin-introductions', 'script': '', 'trigger': '', 'titles': [o['title']],
                                 'descriptions': [o['description']], 'sections': o['introductions'],
                                 'picture': o['picture'], 'hidden': False, 'options': [], 'links': [], 'line': 0})
            self.meta[rid] = {'hasText': True, 'category': 'origins', 'hidden': False}
        self.byid = {r['id']: r for r in self.records}
        self.order = {r['id']: i for i, r in enumerate(self.records)}
        self.families = read(ROOT / 'content/story-families.json') + origin_config
        for sid, fragment in self.fragments.items():
            if 'family' in fragment:  # a reviewed fragment family replaces a legacy family of the same id
                self.families = [f for f in self.families if f['id'] != sid] + [{**fragment['family'], 'id': sid}]
        self.origin_ids = {f['id'] for f in origin_config}

    def kind(self, rid):
        return DOC_KIND.get(self.byid[rid]['kind'], 'event')

    def readable(self, rid):
        r = self.byid[rid]
        if any(s in r['source'] for s in NON_STORY_SOURCES):
            return False
        return bool(self.meta.get(rid, {}).get('hasText')) and not r['hidden']

    # -------------------------------------------------------------------- edges ---
    def build_edges(self):
        self.out = collections.defaultdict(list)
        self.triggers = collections.defaultdict(list)
        callers = collections.defaultdict(set)
        caller_files = collections.defaultdict(set)
        for c in self.graph['calls']:
            if c['via'] == 'scripted_effect' or c['to'] not in self.byid or c['from'] == c['to']:
                continue
            if c['from'] in self.byid:
                if any(s in self.byid[c['from']]['source'] for s in NON_STORY_SOURCES):
                    self.triggers[c['to']].append(c)
                    continue
                self.out[c['from']].append(c)
                callers[c['to']].add(c['from'])
                caller_files[c['to']].add(self.byid[c['from']]['source'])
            else:
                self.triggers[c['to']].append(c)
        self.callers = callers
        # Shared helpers (e.g. the generic contact reports, archaeology dig incidents) are not part of their callers.
        self.hubs = {t for t, s in callers.items() if (len(s) >= 10 and len(caller_files[t]) >= 3) or len(s) >= 25}
        self.hubs |= {h for h in self.hub_review['hubs'] if h in self.byid}
        self.hubs -= set(self.hub_review.get('notHubs', []))
        self.report['hubs'] = len(self.hubs)

    def composite(self, src):
        """Outgoing edges of `src` to readable docs, folding hidden routers into the edge context."""
        if src in self.composite_cache:
            return self.composite_cache[src]
        results = []

        def go(node, segments, seen, depth):
            for call in self.out.get(node, []):
                target = call['to']
                if target in seen or len(results) > 400:
                    continue
                if target in self.hubs and not self.readable(target):
                    self.report['hidden_hub_edges'] += 1
                    continue
                if self.readable(target) or target in self.hubs:
                    results.append((target, segments + [call]))
                elif depth < 10:
                    go(target, segments + [call], seen | {target}, depth + 1)
        go(src, [], {src}, 0)
        self.composite_cache[src] = results
        return results

    def reviewed_edges(self):
        """Reviewed bridges and origin openings are tree edges, keyed by their source doc."""
        extra = collections.defaultdict(list)
        for bridge in self.bridges:
            if bridge.get('annotate'):
                continue
            if bridge['from'] not in self.byid or bridge['to'] not in self.byid:
                self.report['bridge_missing_record'] += 1
                continue
            info = {'kind': 'bridge', 'label': bridge['label'], 'conditional': bridge.get('conditional', False),
                    'source': f"content/stories/{bridge.get('fragment')}.json"}
            if 'choice' in bridge:
                keys = [o['label'].get('key', '') for o in self.byid[bridge['from']]['options']]
                if bridge['choice'] not in keys:
                    raise ValueError('Missing reviewed choice ' + bridge['choice'])
                info['optionIndex'] = keys.index(bridge['choice'])
                info['option'] = bridge['choice']
            if 'requiresVisited' in bridge:
                info['requiresVisited'] = bridge['requiresVisited']
            extra[bridge['from']].append((bridge['to'], info))
        self.openings_start = {'origin-intro:' + sid for sid in self.openings}
        for sid, opening in self.openings.items():
            start = 'origin-intro:' + sid
            for key in opening['targets']:
                if key not in self.byid:
                    raise ValueError(f'Missing origin opening {sid}: {key}')
                extra[start].append((key, {'kind': 'entry', 'label': opening.get('labels', {}).get(key, opening['label']),
                                           'conditional': True, 'source': f'content/stories/{sid}.json'}))
        return extra

    # -------------------------------------------------------------------- roots ---
    def families_membership(self):
        member_of = {}
        self.family_conf = {}
        for f in self.families:
            self.family_conf[f['id']] = f
            for r in self.records:
                if (r['id'] in f.get('members', []) or any(r['source'].endswith(s) for s in f.get('sources', []))
                        or any(r['id'].startswith(p) for p in f.get('prefixes', []))
                        or any(r['eventId'].split('.')[0] == ran['namespace'] and (not ran.get('source') or r['source'].endswith(ran['source']))
                               and r['eventId'].split('.')[-1].isdigit() and ran['min'] <= int(r['eventId'].split('.')[-1]) <= ran['max']
                               for ran in f.get('ranges', []))):
                    member_of.setdefault(r['id'], f['id'])
        for sid, fragment in self.fragments.items():
            for rid in fragment.get('include', []):
                if rid not in self.byid:
                    raise ValueError(f'{sid}: included record no longer exists: {rid}')
                member_of[rid] = sid
            for rid in fragment.get('exclude', []):
                if member_of.get(rid) == sid:
                    del member_of[rid]
        self.member_of = member_of

    def find_roots(self):
        """Root components: strongly connected components of the narrative graph with no outside caller."""
        adj = collections.defaultdict(set)
        for src, calls in self.out.items():
            for c in calls:
                if c['to'] not in self.hubs:  # a hub's own outcomes belong to the hub's story
                    adj[src].add(c['to'])
        for src, edges in self.extra_edges.items():
            for target, _ in edges:
                adj[src].add(target)
        nodes = [r['id'] for r in self.records]
        comp = strongly_connected(nodes, adj)
        external = set()
        for src, targets in adj.items():
            for t in targets:
                if comp[src] != comp[t]:
                    external.add(comp[t])
        members = collections.defaultdict(list)
        for rid in nodes:
            members[comp[rid]].append(rid)
        roots = []
        for c, rids in members.items():
            if c in external:
                continue
            free = [r for r in rids if r not in self.member_of]
            if not free or not any(self.readable(r) or self.composite(r) for r in free):
                continue
            entries = sorted(free, key=lambda r: (not self.triggers.get(r), not self.readable(r), self.order[r]))
            roots.append(entries)
        # Hubs are stories of their own (unless a curated family owns them).
        for hub in sorted(self.hubs):
            if hub not in self.member_of and (self.readable(hub) or self.composite(hub)) and not any(hub in e for e in roots):
                roots.append([hub])
        # A root whose every readable outcome belongs to one curated family is that family's entry
        # (e.g. the precursor anomaly categories that open a precursor investigation).
        kept = []
        for entries in roots:
            targets = {t for rid in entries for t, _ in self.composite(rid) if t not in self.hubs and t not in entries}
            owners = {self.member_of.get(t) for t in targets}
            if targets and len(owners) == 1 and None not in owners:
                family = owners.pop()
                for rid in entries:
                    self.member_of[rid] = family
                self.report['absorbed_into_family'] += 1
                continue
            kept.append(entries)
        # Roots fired only by the same game container (a contract, operation, megastructure, first-contact stage,
        # relic, resolution...) form one story; generic on_actions never group unrelated events.
        by_container = collections.defaultdict(list)
        final = []
        for entries in kept:
            containers = {c['from'] for rid in entries for c in self.triggers.get(rid, [])}
            single = next(iter(containers)) if len(containers) == 1 else None
            if single and ':' in single and not single.startswith(('on_actions:', 'scripted_effects:')):
                by_container[single].append(entries)
            else:
                final.append(entries)
        for container, groups in by_container.items():
            merged = [rid for entries in groups for rid in entries]
            final.append(merged)
            if len(groups) > 1:
                self.report['container_groups'] += 1
                self.container_of.update({rid: container for rid in merged})
        self.root_of = {}
        return final

    # -------------------------------------------------------------------- story ---
    def root_rank(self, rid):
        kind = self.kind(rid)
        return (ROOT_PRIORITY.index(kind) if kind in ROOT_PRIORITY else 99, 0 if self.readable(rid) else 1, self.order[rid])

    def category(self, rid):
        r = self.byid[rid]
        kind = self.kind(rid)
        source = (r['source'] + ' ' + r['id']).lower()
        if kind == 'rift':
            return 'rifts'
        if kind == 'site':
            return 'precursors'
        if kind == 'anomaly':
            return 'precursors' if 'precursor' in source else 'exploration'
        for cat, patterns in CATEGORY_FILES:
            if any(p in source for p in patterns):
                return cat
        return 'stories'

    def via(self, segments):
        """Readable description of how a composite edge is reached."""
        out = {}
        first_seg = segments[0]
        option = next((p for p in first_seg['path'] if p['k'] == 'option'), None)
        if option:
            out['option'] = option['key']
            out['optionIndex'] = option['index']
        chance, random, conditions, delay, group, hooks = 1.0, False, [], [], None, []
        for seg in segments:
            for p in seg['path']:
                if p['k'] in ('random_list', 'random_events', 'anomaly_outcome') and 'group' in p:
                    random = True
                    if p.get('total'):
                        chance *= p['weight'] / p['total']
                    if p.get('modified') or p.get('modifiers'):
                        out['modified'] = True
                    if group is None:
                        group = f"r{p['group']}"
                elif p['k'] == 'random':
                    random = True
                    try:
                        chance *= float(p['chance']) / 100
                    except (TypeError, ValueError):
                        out['modified'] = True
                elif p['k'] in ('if', 'else_if', 'else'):
                    conditions.append({'limit': p.get('limit', ''), 'not': p.get('not', [])})
                    if group is None:
                        group = f"c{p['chain']}"
                elif p['k'] in ('on_success', 'on_fail', 'stage', 'on_first_enter', 'on_progress_complete',
                                'on_fail_complete', 'on_monthly', 'after', 'immediate', 'on_roll_failed', 'on_spawn'):
                    hooks.append(p['k'] if p['k'] != 'stage' else 'stage:' + str(p.get('name', '')))
            if seg.get('delay'):
                delay.append(seg['delay'])
            if seg['via'] in ('on_roll_failed', 'set_next_astral_rift_event', 'stage_event'):
                hooks.append(seg['via'])
        if random:
            out['chance'] = round(chance, 4)
        if group:
            out['group'] = group
        if delay:
            out['delay'] = delay
        if hooks:
            out['hooks'] = hooks
        when = []
        for c in conditions:
            script = c['limit']
            negated = ' '.join(f'NOT = {{ {n[n.find("{") + 1:n.rfind("}")]} }}' for n in c['not'] if '{' in n)
            dnf = self.cond.compile((script[script.find('{') + 1:script.rfind('}')] if '{' in script else '') + ' ' + negated)
            if dnf:
                when.append(dnf)
        if when:
            out['when'] = when
        kind = 'option' if option else 'random' if random else 'condition' if conditions else (
            'project' if 'on_success' in hooks or 'on_fail' in hooks else 'stage' if any(h.startswith('stage') for h in hooks)
            else 'delay' if delay else 'sequence')
        if 'on_roll_failed' in hooks:
            kind = 'failure'
        if first_seg['via'] == 'anomaly_outcome' and not option:
            kind = 'random' if random and out.get('chance', 1) < 1 else 'research'
        out['kind'] = kind
        out['source'] = f"{first_seg['file']}:{first_seg['line']}"
        if len(segments) > 1:
            out['through'] = [s['to'] for s in segments[:-1]]
        return out

    def stage_sequence(self, rid):
        """Archaeological site and situation stages run in definition order, not as simultaneous children."""
        if self.kind(rid) not in ('site', 'situation'):
            return []
        ordered = []
        for t, segs in self.composite(rid):
            if any(p['k'] == 'stage' for p in segs[0]['path']) and t not in ordered:
                ordered.append(t)
        return ordered if len(ordered) > 1 else []

    def doc(self, rid):
        r = self.byid[rid]
        descriptions = [d for d in r['descriptions'] if d['zh'] or d['en']]
        chapter = {'id': rid, 'kind': self.kind(rid), 'title': bilingual(r['titles'][0]) if r['titles'] else {'zh': '', 'en': ''},
                   'texts': [bilingual(d) for d in descriptions], 'sections': [bilingual(d) for d in r['sections'] if d['zh'] or d['en']],
                   'image': r['picture']['url'] if r['picture'] else None, 'hidden': False, 'choices': [], 'next': [],
                   'source': {'file': r['source'], 'line': r.get('line', 0)}}
        body = []
        if self.kind(rid) == 'event' and r['script']:
            try:
                top = parse(r['script'])
                body = top[0]['v'] if top and isinstance(top[0]['v'], list) else []
            except ValueError:
                self.report['unparsed_docs'] += 1
        key_index = {}
        for i, d in enumerate(descriptions):
            key_index.setdefault(d['key'], i)
        passages = self.cond.passages(body, key_index) if body else []
        if passages and (len(passages) > 1 or any('when' in p for ps in passages for p in ps['pieces']) or any('when' in ps for ps in passages)):
            chapter['body'] = passages
        option_nodes = [x['v'] for x in body if x['k'] == 'option' and isinstance(x['v'], list)]
        effects = ' '.join(raw(x, r['script']) for x in body if x['k'] in ('immediate', 'after'))
        doc_flags = sorted(set(FLAG_SET.findall(effects)))
        if doc_flags:
            chapter['sets'] = doc_flags
        for index, o in enumerate(r['options']):
            choice = {'key': o['label'].get('key', ''), 'label': bilingual(o['label']),
                      'responses': [bilingual(t) for t in o.get('responses', []) if t['zh'] or t['en']],
                      'tooltips': [bilingual(t) for t in o.get('tooltips', []) if t['zh'] or t['en']],
                      'conditional': bool(o['conditions']), 'next': [],
                      'terminal': bool(re.search(r'(?:finish_astral_rift|destroy_archaeological_site)\s*=\s*yes', o['script']))}
            nodes = option_nodes[index] if index < len(option_nodes) else []
            visible = self.cond.compile_blocks(nodes, ('trigger', 'exclusive_trigger'))
            allow = self.cond.compile_blocks(nodes, ('allow',))
            if visible:
                choice['when'] = visible
            if allow:
                choice['allow'] = allow
            variants = [v for v in o.get('labelVariants', []) if v.get('zh') or v.get('en')]
            if len(variants) > 1:
                choice['labels'] = [{'label': bilingual(v), **({'when': w} if (w := self.cond.compile(v.get('condition', ''))) else {})} for v in variants]
            flags = FLAG_SET.findall(o['script'])
            removed = FLAG_CLEAR.findall(o['script'])
            if flags:
                choice['sets'] = sorted(set(flags))
            if removed:
                choice['clears'] = sorted(set(removed))
            chapter['choices'].append(choice)
        return chapter

    @staticmethod
    def edge_payload(target, info):
        edge = {'target': target, 'kind': info['kind'], 'conditional': bool(info.get('when')) or bool(info.get('modified')),
                'delayed': bool(info.get('delay')), 'sourceKind': info['kind']}
        if info.get('conditional'):
            edge['conditional'] = True
        for key in ('chance', 'group', 'delay', 'when', 'modified', 'through', 'source', 'hooks', 'label', 'requiresVisited'):
            if key in info:
                edge[key] = info[key]
        return edge

    def trigger_labels(self, rid):
        labels = []
        definition = self.graph['definitions'].get(rid, {})
        if definition.get('mtth'):
            labels.append({'zh': '随时间随机发生', 'en': 'Happens randomly over time'})
        elif not self.triggers.get(rid) and not self.callers.get(rid) and self.kind(rid) == 'event':
            labels.append({'zh': '由游戏机制触发（脚本中无直接调用）', 'en': 'Fired by the game engine (no script call found)'})
        for call in self.triggers.get(rid, []):
            folder, _, key = call['from'].partition(':')
            if folder == 'on_actions':
                zh, en = TRIGGER_LABELS.get(key, ('由游戏状态触发', 'Triggered by game state'))
            elif folder in DEF_TRIGGERS:
                zh, en = DEF_TRIGGERS[folder]
            else:
                zh, en = ('由游戏机制触发', 'Triggered by a game mechanic')
            label = {'zh': zh, 'en': en}
            if label not in labels:
                labels.append(label)
        return labels

    @staticmethod
    def delay_days(info):
        total = 0
        for d in info.get('delay', []):
            for unit, factor in (('days', 1), ('months', 30), ('years', 360)):
                try:
                    total += float(d.get(unit, 0) or 0) * factor
                except (TypeError, ValueError):
                    pass
        return total

    @staticmethod
    def preorder(tree):
        out, stack = [], [tree['root']]
        while stack:
            nid = stack.pop()
            out.append(nid)
            stack.extend(reversed(tree['nodes'][nid].get('children', [])))
        return out

    def build_story(self, sid, entries, family, pending):
        """Breadth-first tree from the entries; `pending` docs not yet reached become further entries."""
        chapters, placed = {}, {}
        tree = {'root': 'n0', 'nodes': {'n0': {'doc': None, 'children': []}}}
        counter = [1]
        own = set(entries)

        def allowed(t):
            if not self.readable(t):
                return False
            if t in own:
                return True
            if t in self.hubs and self.member_of.get(t) != family:
                return False
            owner = self.member_of.get(t)
            if owner is not None and owner != family:
                return False
            return self.root_of.get(t, sid) == sid

        def new_node(payload):
            nid = f'n{counter[0]}'
            counter[0] += 1
            tree['nodes'][nid] = payload
            return nid

        def place_entry(rid, info):
            if rid in placed or not allowed(rid):
                return
            chapters.setdefault(rid, self.doc(rid))
            nid = new_node({'doc': rid, 'parent': 'n0', 'via': info, 'children': []})
            tree['nodes']['n0']['children'].append(nid)
            placed[rid] = nid
            expand(nid)

        def expand(first):
            queue = collections.deque([first])
            while queue:
                nid = queue.popleft()
                rid = tree['nodes'][nid]['doc']
                chapter = chapters[rid]
                described = [(t, self.via(s)) for t, s in self.composite(rid)]
                for s in self.suppressed.get(rid, []):
                    before = len(described)
                    described = [(t, i) for t, i in described if not (t == s['to'] and s.get('option') in (None, i.get('option')))]
                    if len(described) == before:
                        self.report['suppress_without_edge'] += 1
                sequence = self.stage_sequence(rid)
                if sequence:
                    described = [(t, i) for t, i in described if t not in sequence[1:]]
                    for previous, following in zip(sequence, sequence[1:]):
                        self.stage_edges[previous] = [(following, {'kind': 'stage', 'hooks': ['stage'], 'source': chapter['source']['file']})]
                reviewed = self.extra_edges.get(rid, []) + self.stage_edges.get(rid, [])
                if rid in self.openings_start:
                    described = []  # reviewed origin openings replace the generic game-start fan-out
                described = [(t, i) for t, i in described
                             if not any(t == rt and i.get('optionIndex') == ri.get('optionIndex') for rt, ri in reviewed)]
                children = sorted(described + reviewed, key=lambda e: (e[1].get('optionIndex', 999), self.delay_days(e[1])))
                seen_edges = set()
                for target, info in children:
                    signature = (target, info.get('optionIndex'))
                    if signature in seen_edges:  # same outcome reached through another router path
                        continue
                    seen_edges.add(signature)
                    edge = self.edge_payload(target, info)
                    index = info.get('optionIndex')
                    if index is not None and index < len(chapter['choices']):
                        chapter['choices'][index]['next'].append(edge)
                    elif not any(e['target'] == target for e in chapter['next']):
                        chapter['next'].append(edge)
                    if not allowed(target):
                        continue
                    if target in placed:
                        tree['nodes'][nid]['children'].append(new_node({'ref': placed[target], 'doc': target, 'parent': nid, 'via': info}))
                        continue
                    chapters[target] = self.doc(target)
                    child = new_node({'doc': target, 'parent': nid, 'via': info, 'children': []})
                    tree['nodes'][nid]['children'].append(child)
                    placed[target] = child
                    queue.append(child)

        for rid in entries:
            triggers = self.trigger_labels(rid)
            info = {'kind': 'entry', **({'triggers': triggers} if triggers else {})}
            if self.readable(rid):
                place_entry(rid, info)
            else:  # hidden router entry: its readable outcomes are the story's openings
                for target, segs in self.composite(rid):
                    place_entry(target, {**self.via(segs), 'kind': 'entry', **({'triggers': triggers} if triggers else {})})
        for rid in pending:
            if rid in placed:
                continue
            triggers = self.trigger_labels(rid)
            info = {'kind': 'entry', 'secondary': True, **({'triggers': triggers} if triggers else {})}
            if self.readable(rid):
                place_entry(rid, info)
                self.report['secondary_entries'] += 1
            else:  # hidden member router: its readable outcomes open further branches of the story
                for target, segs in self.composite(rid):
                    if target not in placed:
                        place_entry(target, {**self.via(segs), **info})
        return chapters, tree, placed

    def compile(self):
        self.prepare()
        self.build_edges()
        self.families_membership()
        self.extra_edges = self.reviewed_edges()
        self.stage_edges = {}
        roots = self.find_roots()
        plan = []
        for fid in dict.fromkeys(self.member_of.values()):
            f = self.family_conf[fid]
            # Members nothing calls (anomaly discovery cards, triggered openings) open the story before their outcomes.
            members = sorted((r for r, o in self.member_of.items() if o == fid),
                             key=lambda r: (any(c not in self.hubs for c in self.callers.get(r, ())), not self.triggers.get(r),
                                            self.kind(r) != 'anomaly', self.order[r]))
            start = f.get('start') if f.get('start') in self.byid else None
            plan.append({'id': fid, 'family': fid, 'entries': ([start] if start else []), 'pending': members})
        used = {p['id'] for p in plan}
        for entries in sorted(roots, key=lambda e: self.root_rank(min(e, key=self.root_rank))):
            primary = min(entries, key=self.root_rank)
            sid = slug(f"{self.kind(primary)}-{primary.split(':')[-1]}")
            while sid in used:
                sid += '-x'
            used.add(sid)
            for rid in entries:
                self.root_of[rid] = sid
            ordered = [primary] + [e for e in entries if e != primary]
            plan.append({'id': sid, 'family': None, 'entries': ordered, 'pending': ordered})
        stories, details, mapping, appearances = [], {}, {}, collections.defaultdict(list)
        for item in plan:
            sid, family = item['id'], item['family']
            chapters, tree, placed = self.build_story(sid, item['entries'], family, item['pending'])
            if not chapters:
                self.report['empty_stories'] += 1
                continue
            ordered_docs = [tree['nodes'][n]['doc'] for n in self.preorder(tree) if 'ref' not in tree['nodes'][n] and tree['nodes'][n]['doc']]
            start = ordered_docs[0]
            fragment = self.fragments.get(sid, {})
            if family:
                f = self.family_conf[family]
                title, category = f['title'], f['category']
                kind = 'origin' if sid in self.origin_ids else 'family'
                if f.get('start') in chapters:
                    start = f['start']
            else:
                primary = item['entries'][0]
                kind = self.kind(primary)
                title = chapters[start]['title']
                category = self.category(primary)
            category = fragment.get('category', category)
            title = fragment.get('title', title)
            if fragment.get('titleFrom'):
                source = self.byid[fragment['titleFrom']]
                title = bilingual(source['titles'][0])
            title = {lang: v or ('未命名故事' if lang == 'zh' else 'An untitled story') for lang, v in title.items()}
            image = next((chapters[d]['image'] for d in ordered_docs if chapters[d]['image']), None)
            excerpt = next((t for d in ordered_docs for t in chapters[d]['texts'] if t['zh'] or t['en']), {'zh': '', 'en': ''})
            entry = {'id': sid, 'title': title, 'category': category, 'kind': kind, 'image': image, 'start': start,
                     'chapters': len(chapters), 'visible': True, 'excerpt': {k: v[:260] for k, v in excerpt.items()}}
            if fragment.get('review'):
                entry['review'] = {k: fragment['review'][k] for k in ('status', 'date') if k in fragment['review']}
            for rid in ordered_docs:
                appearances[rid].append(sid)
            story = {**entry, 'tree': tree}
            for field in ('groups', 'review'):
                if fragment.get(field):
                    story[field] = fragment[field]
            for group in story.get('groups', []):
                missing = [m for m in group.get('members', []) + ([group['gate']] if group.get('gate') else []) if m not in chapters]
                if missing:
                    raise ValueError(f'{sid}: reviewed group references docs outside the story: {missing}')
            for rid in ordered_docs:
                if rid in self.notes:
                    chapters[rid]['notes'] = self.notes[rid]
            details[sid] = {'story': story, 'chapters': [chapters[d] for d in ordered_docs]}
            stories.append(entry)
        for sid, d in details.items():
            for c in d['chapters']:
                owner = self.member_of.get(c['id']) or self.root_of.get(c['id'])
                if owner in details and c['id'] not in mapping:
                    mapping[c['id']] = owner
        for rid, sids in appearances.items():
            mapping.setdefault(rid, sids[0])
        self.appearances = appearances
        self.apply_reviewed(details, mapping)
        self.write(stories, details, mapping)

    # ------------------------------------------------------------ reviewed facts ---
    def apply_reviewed(self, details, mapping):
        for d in details.values():
            sid = d['story']['id']
            chapter_map = {c['id']: c for c in d['chapters']}
            for bridge in self.bridges:
                if not bridge.get('annotate') or bridge['from'] not in chapter_map:
                    continue
                source = chapter_map[bridge['from']]
                if 'choice' in bridge:
                    source = next((c for c in source['choices'] if c.get('key') == bridge['choice']), None)
                    if source is None:
                        raise ValueError('Missing reviewed choice ' + bridge['choice'])
                existing = next((e for e in source['next'] if e['target'] == bridge['to']), None)
                if not existing:
                    self.report['annotation_without_edge'] += 1
                    continue
                existing['label'] = bridge['label']
                existing['conditional'] = bridge.get('conditional', existing['conditional'])
                if 'requiresVisited' in bridge:
                    existing['requiresVisited'] = bridge['requiresVisited']
            for rid, chapter in chapter_map.items():
                if rid in self.endings:
                    chapter['ending'] = {'label': self.endings[rid]['label'], 'note': self.endings[rid]['note']}
                if rid in self.dialogues:
                    self.apply_dialogue(chapter, self.dialogues[rid])
                if rid in self.readings:
                    self.apply_readings(chapter, self.readings[rid])
                for edges in [chapter['next']] + [c['next'] for c in chapter['choices']]:
                    for edge in edges:
                        edge['story'] = sid if edge['target'] in chapter_map else mapping.get(edge['target'])
                if len(self.appearances[rid]) > 1:
                    chapter['alsoIn'] = [s for s in self.appearances[rid] if s != sid]
            if sid in self.node_labels:
                d['story']['nodeLabels'] = self.node_labels[sid]

    def apply_dialogue(self, chapter, review):
        keys = [c['key'] for c in chapter['choices']]
        if 'states' in review:
            if any(k not in keys for options in review['states'].values() for k in options):
                raise ValueError('Reviewed dialogue state no longer matches source: ' + chapter['id'])
            chapter['dialogue'] = {'states': review['states'], 'transitions': review['transitions'], 'exits': review.get('exits', [])}
            for field in ('consumedTopics', 'edgeRequirements', 'profileLabel', 'stateOrder'):
                if field in review:
                    chapter['dialogue'][field] = review[field]
            if 'responseProfiles' in review:
                chapter['dialogue']['responseProfiles'] = []
                for profile in review['responseProfiles']:
                    excluded = [i for i, k in enumerate(keys) if k in profile.get('excludedKeys', [])]
                    for key, occurrence in profile['occurrences'].items():
                        matches = [i for i, k in enumerate(keys) if k == key]
                        if not 0 <= occurrence < len(matches):
                            raise ValueError('Missing reviewed response instance: ' + chapter['id'])
                        excluded.extend(i for i in matches if i != matches[occurrence])
                    chapter['dialogue']['responseProfiles'].append({'label': profile['label'], 'excluded': excluded})
        else:
            if any(k not in keys for k in review['steps']):
                raise ValueError('Reviewed dialogue no longer matches source: ' + chapter['id'])
            chapter['dialogue'] = {'steps': [keys.index(k) for k in review['steps']]}
        if 'textProfiles' in review:
            texts = [d for d in self.byid[chapter['id']]['descriptions'] if d['zh'] or d['en']]
            chapter['dialogue']['textProfiles'] = []
            for profile in review['textProfiles']:
                matches = [i for i, d in enumerate(texts) if d['key'] == profile['text']]
                if len(matches) != 1:
                    raise ValueError('Missing reviewed dialogue passage: ' + chapter['id'])
                chapter['dialogue']['textProfiles'].append({'label': profile['label'], 'textIndex': matches[0], 'after': profile['after']})
        variants_profiles = review.get('labelProfiles', {})
        for index, option in enumerate(self.byid[chapter['id']]['options']):
            variants = option.get('labelVariants', [])
            if len(variants) > 1 and all(v['key'] in variants_profiles for v in variants):
                chapter['choices'][index]['labelVariants'] = [{'label': bilingual(v), 'profile': variants_profiles[v['key']]} for v in variants]

    def apply_readings(self, chapter, review):
        texts = [d for d in self.byid[chapter['id']]['descriptions'] if d['zh'] or d['en']]
        chapter['readings'] = []
        for profile in review['profiles']:
            text_indices, choice_indices = [], []
            for key in profile['texts']:
                matches = [i for i, d in enumerate(texts) if d['key'] == key]
                if len(matches) != 1:
                    raise ValueError('Invalid reviewed reading passage ' + chapter['id'] + ':' + key)
                text_indices.append(matches[0])
            for selector in profile['choices']:
                key = selector['key'] if isinstance(selector, dict) else selector
                matches = [i for i, c in enumerate(chapter['choices']) if c['key'] == key]
                if isinstance(selector, dict):
                    if len(matches) != selector['count'] or not 0 <= selector['occurrence'] < len(matches):
                        raise ValueError('Invalid reviewed repeated choice ' + chapter['id'] + ':' + key)
                    choice_indices.append(matches[selector['occurrence']])
                else:
                    if len(matches) != 1:
                        raise ValueError('Invalid reviewed reading choice ' + chapter['id'] + ':' + key)
                    choice_indices.append(matches[0])
            reading = {'label': profile['label'], 'textIndices': text_indices, 'choiceIndices': choice_indices}
            if 'afterChoice' in profile:
                reading['afterChoice'] = profile['afterChoice']
            chapter['readings'].append(reading)

    # ------------------------------------------------------------------- output ---
    def write(self, stories, details, mapping):
        out = ROOT / 'public/stories'
        for sid, d in details.items():
            summary = ROOT / 'public/summaries' / f'{sid}.md'
            if summary.is_file():
                d['summary'] = {'text': summary.read_text(encoding='utf-8-sig'), 'path': f'summaries/{sid}.md'}
            dump(out / f'{sid}.json', d)
        stories.sort(key=lambda s: (s['kind'] not in ('origin', 'family'), -s['chapters'], s['id']))
        dump(out / 'index.json', {'version': 4, 'gameVersion': self.version, 'stories': stories, 'recordToStory': mapping})
        keep = {s['id'] + '.json' for s in stories} | {'index.json'}
        for p in out.glob('*.json'):
            if p.name not in keep and p.resolve().parent == out.resolve():
                p.unlink()
        orphans = sorted(set(self.fragments) - {s['id'] for s in stories})
        if orphans:
            self.report['orphan_fragments'] = len(orphans)
        review = collections.defaultdict(collections.Counter)
        for s in stories:
            review[s['category']][s.get('review', {}).get('status', 'unreviewed')] += 1
        by_category = collections.Counter(s['category'] for s in stories)
        sizes = collections.Counter('1' if s['chapters'] == 1 else '2-3' if s['chapters'] <= 3 else '4-9' if s['chapters'] <= 9
                                    else '10-29' if s['chapters'] <= 29 else '30+' for s in stories)
        readable = [r['id'] for r in self.records if self.readable(r['id'])]
        coverage = {'model': 4, 'records': len(self.records), 'readableDocs': len(readable),
                    'assignedDocs': sum(1 for r in readable if r in mapping),
                    'unassignedDocs': sorted(r for r in readable if r not in mapping)[:50],
                    'sharedDocs': sum(1 for v in self.appearances.values() if len(v) > 1),
                    'stories': len(stories), 'byCategory': dict(by_category), 'sizes': dict(sizes), 'hubs': len(self.hubs),
                    'review': {k: dict(v) for k, v in review.items()}, 'orphanFragments': orphans, 'report': dict(self.report)}
        dump(ROOT / 'public/data/story-coverage.json', coverage)
        print(json.dumps(coverage, ensure_ascii=False, indent=1))


