    @staticmethod
    def delay_days(info):
        total = 0
        for d in info.get('delay', []):
            for unit, factor in (('days', 1), ('months', 30), ('years', 360)):
                try:
                    total += float(d.get(unit, 0) or 0) * factor
                except (TypeError, ValueError):
                    pass
        return total

    @staticmethod
    def preorder(tree):
        out, stack = [], [tree['root']]
        while stack:
            nid = stack.pop()
            out.append(nid)
            stack.extend(reversed(tree['nodes'][nid].get('children', [])))
        return out

    def build_story(self, sid, entries, family, pending):
        """Breadth-first tree from the entries; `pending` docs not yet reached become further entries."""
        chapters, placed = {}, {}
        tree = {'root': 'n0', 'nodes': {'n0': {'doc': None, 'children': []}}}
        counter = [1]
        own = set(entries)

        def allowed(t):
            if not self.readable(t) or t in self.excluded.get(sid, ()):
                return False
            if t in own:
                return True
            if t in self.hubs and self.member_of.get(t) != family:
                return False
            owner = self.member_of.get(t)
            if owner is not None and owner != family:
                return False
            return self.root_of.get(t, sid) == sid

        def new_node(payload):
            nid = f'n{counter[0]}'
            counter[0] += 1
            tree['nodes'][nid] = payload
            return nid

        def place_entry(rid, info):
            if rid in placed or not allowed(rid):
                return
            chapters.setdefault(rid, self.doc(rid))
            nid = new_node({'doc': rid, 'parent': 'n0', 'via': info, 'children': []})
            tree['nodes']['n0']['children'].append(nid)
            placed[rid] = nid
            expand(nid)

        def expand(first):
            queue = collections.deque([first])
            while queue:
                nid = queue.popleft()
                rid = tree['nodes'][nid]['doc']
                chapter = chapters[rid]
                described = [(t, self.via(s)) for t, s in self.composite(rid)]
                for s in self.suppressed.get(rid, []):
                    before = len(described)
                    described = [(t, i) for t, i in described if not (t == s['to'] and s.get('option') in (None, i.get('option')))]
                    if len(described) == before:
                        self.report['suppress_without_edge'] += 1
                sequence = self.stage_sequence(rid)
                if sequence:
                    described = [(t, i) for t, i in described if t not in sequence[1:]]
                    for previous, following in zip(sequence, sequence[1:]):
                        self.stage_edges[previous] = [(following, {'kind': 'stage', 'hooks': ['stage'], 'source': chapter['source']['file']})]
                stage = [(t, i) for t, i in self.stage_edges.get(rid, [])
                         if not any(s['to'] == t and 'option' not in s for s in self.suppressed.get(rid, []))]
                reviewed = self.extra_edges.get(rid, []) + stage
                if rid in self.openings_start:
                    described = []  # reviewed origin openings replace the generic game-start fan-out
                described = [(t, i) for t, i in described
                             if not any(t == rt and i.get('optionIndex') == ri.get('optionIndex') for rt, ri in reviewed)]
                children = sorted(described + reviewed, key=lambda e: (e[1].get('optionIndex', 999), self.delay_days(e[1])))
                seen_edges = set()
                for target, info in children:
                    signature = (target, info.get('optionIndex'))
                    if signature in seen_edges:  # same outcome reached through another router path
                        continue
                    seen_edges.add(signature)
                    if not self.readable(target):  # e.g. a reviewed link into an observer-mode notification
                        self.report['edges_to_non_story'] += 1
                        continue
                    edge = self.edge_payload(target, info)
                    index = info.get('optionIndex')
                    if index is not None and index < len(chapter['choices']):
                        chapter['choices'][index]['next'].append(edge)
                    elif not any(e['target'] == target for e in chapter['next']):
                        chapter['next'].append(edge)
                    if not allowed(target) or (info.get('external') and target not in placed and target not in own):
                        continue
                    if target in placed:
                        tree['nodes'][nid]['children'].append(new_node({'ref': placed[target], 'doc': target, 'parent': nid, 'via': info}))
                        continue
                    chapters[target] = self.doc(target)
                    child = new_node({'doc': target, 'parent': nid, 'via': info, 'children': []})
                    tree['nodes'][nid]['children'].append(child)
                    placed[target] = child
                    queue.append(child)

        for rid in entries:
            triggers = self.trigger_labels(rid)
            info = {'kind': 'entry', **({'triggers': triggers} if triggers else {})}
            if self.readable(rid):
                place_entry(rid, info)
            else:  # hidden router entry: its readable outcomes are the story's openings
                for target, segs in self.composite(rid):
                    place_entry(target, {**self.via(segs), 'kind': 'entry', **({'triggers': triggers} if triggers else {})})
        for rid in pending:
            if rid in placed:
                continue
            triggers = self.trigger_labels(rid)
            info = {'kind': 'entry', 'secondary': True, **({'triggers': triggers} if triggers else {})}
            if self.readable(rid):
                place_entry(rid, info)
                self.report['secondary_entries'] += 1
            else:  # hidden member router: its readable outcomes open further branches of the story
                for target, segs in self.composite(rid):
                    if target not in placed:
                        place_entry(target, {**self.via(segs), **info})
        return chapters, tree, placed

    def compile(self):
        self.prepare()
        self.build_edges()
        self.families_membership()
        self.extra_edges = self.reviewed_edges()
        self.stage_edges = {}
        roots = self.find_roots()
        plan = []
        for fid in dict.fromkeys(self.member_of.values()):
            f = self.family_conf[fid]
            # Members nothing calls (anomaly discovery cards, triggered openings) open the story before their outcomes.
            members = sorted((r for r, o in self.member_of.items() if o == fid),
                             key=lambda r: (any(c not in self.hubs for c in self.callers.get(r, ())), not self.triggers.get(r),
                                            self.kind(r) != 'anomaly', self.order[r]))
            start = f.get('start') if f.get('start') in self.byid else None
            plan.append({'id': fid, 'family': fid, 'entries': ([start] if start else []), 'pending': members})
        used = {p['id'] for p in plan}
        for entries in sorted(roots, key=lambda e: self.root_rank(min(e, key=self.root_rank))):
            primary = min(entries, key=self.root_rank)
            sid = slug(f"{self.kind(primary)}-{primary.split(':')[-1]}")
            while sid in used:
                sid += '-x'
            used.add(sid)
            for rid in entries:
                self.root_of[rid] = sid
            ordered = [primary] + [e for e in entries if e != primary]
            plan.append({'id': sid, 'family': None, 'entries': ordered, 'pending': ordered})
        stories, details, mapping, appearances = [], {}, {}, collections.defaultdict(list)
        for item in plan:
            sid, family = item['id'], item['family']
            chapters, tree, placed = self.build_story(sid, item['entries'], family, item['pending'])
            if not chapters:
                self.report['empty_stories'] += 1
                continue
            ordered_docs = [tree['nodes'][n]['doc'] for n in self.preorder(tree) if 'ref' not in tree['nodes'][n] and tree['nodes'][n]['doc']]
            start = ordered_docs[0]
            fragment = self.fragments.get(sid, {})
            if family:
                f = self.family_conf[family]
                title, category = f['title'], f['category']
                kind = 'origin' if sid in self.origin_ids else 'family'
                if f.get('start') in chapters:
                    start = f['start']
            else:
                primary = item['entries'][0]
                kind = self.kind(primary)
                title = chapters[start]['title']
                category = self.category(primary)
            category = fragment.get('category', category)
            title = fragment.get('title', title)
            if fragment.get('titleFrom'):
                source = self.byid[fragment['titleFrom']]
                title = bilingual(source['titles'][0])
            title = {lang: v or ('未命名故事' if lang == 'zh' else 'An untitled story') for lang, v in title.items()}
            image = next((chapters[d]['image'] for d in ordered_docs if chapters[d]['image']), None)
            excerpt = next((t for d in ordered_docs for t in chapters[d]['texts'] if t['zh'] or t['en']), {'zh': '', 'en': ''})
            entry = {'id': sid, 'title': title, 'category': category, 'kind': kind, 'image': image, 'start': start,
                     'chapters': len(chapters), 'visible': True, 'excerpt': {k: v[:260] for k, v in excerpt.items()}}
            if fragment.get('review'):
                entry['review'] = {k: fragment['review'][k] for k in ('status', 'date') if k in fragment['review']}
            for rid in ordered_docs:
                appearances[rid].append(sid)
            story = {**entry, 'tree': tree}
            for field in ('groups', 'review'):
                if fragment.get(field):
                    story[field] = fragment[field]
            for group in story.get('groups', []):
                dropped = [m for m in group.get('members', []) if m in self.byid and not self.readable(m)]
                if dropped:  # e.g. observer-mode notifications, which are not stories
                    group['members'] = [m for m in group['members'] if m not in dropped]
                    self.report['group_members_not_stories'] += len(dropped)
                missing = [m for m in group.get('members', []) + ([group['gate']] if group.get('gate') else []) if m not in chapters]
                if missing:
                    # Usually another reviewer's change moved these docs; keep the rest and report for follow-up.
                    group['members'] = [m for m in group.get('members', []) if m in chapters]
                    if group.get('gate') not in chapters:
                        group.pop('gate', None)
                    self.warnings.append(f'{sid}: group references docs outside the story: {missing}')
            for rid in ordered_docs:
                if rid in self.notes:
                    chapters[rid]['notes'] = self.notes[rid]
                if rid in self.unreachable:
                    chapters[rid]['unreachable'] = self.unreachable[rid]
                if chapters[rid].get('names'):
                    chapters[rid] = {**chapters[rid], 'names': self.reviewed_names(fragment, rid, chapters[rid]['names'])}
            details[sid] = {'story': story, 'chapters': [chapters[d] for d in ordered_docs]}
            stories.append(entry)
        for sid, d in details.items():
            for c in d['chapters']:
                owner = self.member_of.get(c['id']) or self.root_of.get(c['id'])
                if owner in details and c['id'] not in mapping:
                    mapping[c['id']] = owner
        for rid, sids in appearances.items():
            mapping.setdefault(rid, sids[0])
        self.appearances = appearances
        self.apply_reviewed(details, mapping)
        self.write(stories, details, mapping)

    # ------------------------------------------------------------ reviewed facts ---
    def apply_reviewed(self, details, mapping):
        for d in details.values():
            sid = d['story']['id']
            chapter_map = {c['id']: c for c in d['chapters']}
            for bridge in self.bridges:
                if not bridge.get('annotate') or bridge['from'] not in chapter_map:
                    continue
                source = chapter_map[bridge['from']]
                if 'choice' in bridge:
                    source = next((c for c in source['choices'] if c.get('key') == bridge['choice']), None)
                    if source is None:
                        raise ValueError('Missing reviewed choice ' + bridge['choice'])
                existing = next((e for e in source['next'] if e['target'] == bridge['to']), None)
                if not existing:
                    self.report['annotation_without_edge'] += 1
                    continue
                existing['label'] = bridge['label']
                existing['conditional'] = bridge.get('conditional', existing['conditional'])
                if 'requiresVisited' in bridge:
                    existing['requiresVisited'] = bridge['requiresVisited']
            for rid, chapter in chapter_map.items():
                if rid in self.endings:
                    chapter['ending'] = {'label': self.endings[rid]['label'], 'note': self.endings[rid]['note']}
                if rid in self.dialogues:
                    self.apply_dialogue(chapter, self.dialogues[rid])
                if rid in self.readings:
                    self.apply_readings(chapter, self.readings[rid])
                for edges in [chapter['next']] + [c['next'] for c in chapter['choices']]:
                    for edge in edges:
                        edge['story'] = sid if edge['target'] in chapter_map else mapping.get(edge['target'])
                if len(self.appearances[rid]) > 1:
                    chapter['alsoIn'] = [s for s in self.appearances[rid] if s != sid]
            if sid in self.node_labels:
                d['story']['nodeLabels'] = self.node_labels[sid]

    def apply_dialogue(self, chapter, review):
        keys = [c['key'] for c in chapter['choices']]
        if 'states' in review:
            if any(k not in keys for options in review['states'].values() for k in options):
                raise ValueError('Reviewed dialogue state no longer matches source: ' + chapter['id'])
            chapter['dialogue'] = {'states': review['states'], 'transitions': review['transitions'], 'exits': review.get('exits', [])}
            for field in ('consumedTopics', 'edgeRequirements', 'profileLabel', 'stateOrder'):
                if field in review:
                    chapter['dialogue'][field] = review[field]
            if 'responseProfiles' in review:
                chapter['dialogue']['responseProfiles'] = []
                for profile in review['responseProfiles']:
                    excluded = [i for i, k in enumerate(keys) if k in profile.get('excludedKeys', [])]
                    for key, occurrence in profile['occurrences'].items():
                        matches = [i for i, k in enumerate(keys) if k == key]
                        if not 0 <= occurrence < len(matches):
                            raise ValueError('Missing reviewed response instance: ' + chapter['id'])
                        excluded.extend(i for i in matches if i != matches[occurrence])
                    chapter['dialogue']['responseProfiles'].append({'label': profile['label'], 'excluded': excluded})
        else:
            if any(k not in keys for k in review['steps']):
                raise ValueError('Reviewed dialogue no longer matches source: ' + chapter['id'])
            chapter['dialogue'] = {'steps': [keys.index(k) for k in review['steps']]}
        if 'textProfiles' in review:
            texts = [d for d in self.byid[chapter['id']]['descriptions'] if d['zh'] or d['en']]
            chapter['dialogue']['textProfiles'] = []
            for profile in review['textProfiles']:
                matches = [i for i, d in enumerate(texts) if d['key'] == profile['text']]
                if len(matches) != 1:
                    raise ValueError('Missing reviewed dialogue passage: ' + chapter['id'])
                chapter['dialogue']['textProfiles'].append({'label': profile['label'], 'textIndex': matches[0], 'after': profile['after']})
        variants_profiles = review.get('labelProfiles', {})
        for index, option in enumerate(self.byid[chapter['id']]['options']):
            variants = option.get('labelVariants', [])
            if len(variants) > 1 and all(v['key'] in variants_profiles for v in variants):
                chapter['choices'][index]['labelVariants'] = [{'label': bilingual(v), 'profile': variants_profiles[v['key']]} for v in variants]

    def apply_readings(self, chapter, review):
        texts = [d for d in self.byid[chapter['id']]['descriptions'] if d['zh'] or d['en']]
        chapter['readings'] = []
        for profile in review['profiles']:
            text_indices, choice_indices = [], []
            for key in profile['texts']:
                matches = [i for i, d in enumerate(texts) if d['key'] == key]
                if len(matches) != 1:
                    raise ValueError('Invalid reviewed reading passage ' + chapter['id'] + ':' + key)
                text_indices.append(matches[0])
            for selector in profile['choices']:
                key = selector['key'] if isinstance(selector, dict) else selector
                matches = [i for i, c in enumerate(chapter['choices']) if c['key'] == key]
                if isinstance(selector, dict):
                    if len(matches) != selector['count'] or not 0 <= selector['occurrence'] < len(matches):
                        raise ValueError('Invalid reviewed repeated choice ' + chapter['id'] + ':' + key)
                    choice_indices.append(matches[selector['occurrence']])
                else:
                    if len(matches) != 1:
                        raise ValueError('Invalid reviewed reading choice ' + chapter['id'] + ':' + key)
                    choice_indices.append(matches[0])
            reading = {'label': profile['label'], 'textIndices': text_indices, 'choiceIndices': choice_indices}
            if 'afterChoice' in profile:
                reading['afterChoice'] = profile['afterChoice']
            chapter['readings'].append(reading)

