    @staticmethod
    def common_glyphs(details, limit=3000):
        """The most frequent non-ASCII characters of the Chinese text, most frequent first. The reader lays them out
        during idle time so a story's first open does not pay Chrome's first-use cost per CJK glyph (≈0.04 ms each)."""
        counts = collections.Counter()
        def walk(node):
            if isinstance(node, dict):
                for k, v in node.items():
                    if k == 'zh' and isinstance(v, str):
                        counts.update(ch for ch in v if ord(ch) > 0x2000 and not ch.isspace())
                    else:
                        walk(v)
            elif isinstance(node, list):
                for v in node:
                    walk(v)
        walk(details)
        return ''.join(ch for ch, _ in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:limit])

    @staticmethod
    def local_groups(node, ids=None):
        """Renumber random/if-chain group ids (global call-graph counters) per story in order of appearance, so a
        change elsewhere in the game graph does not rewrite every story file. Ids only need to be unique per story."""
        ids = {} if ids is None else ids
        if isinstance(node, dict):
            for k, v in node.items():
                if k == 'group' and isinstance(v, str) and re.fullmatch(r'[rc]\d+', v):
                    node[k] = ids.setdefault(v, f'{v[0]}{len(ids) + 1}')
                else:
                    Compiler.local_groups(v, ids)
        elif isinstance(node, list):
            for v in node:
                Compiler.local_groups(v, ids)
        return node

    LOC_REF = re.compile(r'\$([A-Za-z_][\w.]*)\$')

    def expand_ref(self, text, lang, depth=0):
        """Expand $KEY$ localisation references the way the game does (trait, resource, concept names). Runtime
        values ($COUNT$, $REQUIRED$ …) have no localisation entry and are left for the reader."""
        def sub(m):
            entry = self.loc.get(m.group(1))
            value = entry.get(lang) if entry else None
            if not value or depth > 3:
                return m.group(0)
            return self.expand_ref(value, lang, depth + 1)
        return self.LOC_REF.sub(sub, text) if '$' in text else text

    def expand_refs(self, node):
        if isinstance(node, dict):
            if set(node) >= {'zh', 'en'} and isinstance(node.get('zh'), str) and isinstance(node.get('en'), str):
                return {**node, 'zh': self.expand_ref(node['zh'], 'zh'), 'en': self.expand_ref(node['en'], 'en')}
            return {k: self.expand_refs(v) for k, v in node.items()}
        if isinstance(node, list):
            return [self.expand_refs(v) for v in node]
        return node

    def write(self, stories, details, mapping):
        out = ROOT / 'public/stories'
        for sid, d in details.items():
            self.local_groups(d)
            summary = ROOT / 'public/summaries' / f'{sid}.md'
            if summary.is_file():
                d['summary'] = {'text': summary.read_text(encoding='utf-8-sig'), 'path': f'summaries/{sid}.md'}
            d['chapters'] = self.expand_refs(d['chapters'])
            d['story'] = self.expand_refs(d['story'])
            dump(out / f'{sid}.json', d)
        stories.sort(key=lambda s: (s['kind'] not in ('origin', 'family'), -s['chapters'], s['id']))
        # The catalogue needs only identities and art at first paint; excerpts and the record map load later.
        dump(out / 'index.json', {'version': 4, 'gameVersion': self.version,
                                  'stories': [{k: v for k, v in s.items() if k != 'excerpt'} for s in stories]})
        dump(out / 'excerpts.json', {s['id']: self.expand_refs(s['excerpt']) for s in stories})
        dump(out / 'records.json', mapping)
        dump(out / 'names.json', self.expand_refs(self.compile_names()))
        dump(out / 'profile.json', self.profile_options())
        dump(out / 'glyphs.json', {'zh': self.common_glyphs(details)})
        keep = {s['id'] + '.json' for s in stories} | {'index.json', 'excerpts.json', 'records.json', 'names.json', 'profile.json', 'glyphs.json'}
        for p in out.glob('*.json'):
            if p.name not in keep and p.resolve().parent == out.resolve():
                p.unlink()
        orphans = sorted(set(self.fragments) - {s['id'] for s in stories})
        if orphans:
            self.report['orphan_fragments'] = len(orphans)
        review = collections.defaultdict(collections.Counter)
        for s in stories:
            review[s['category']][s.get('review', {}).get('status', 'unreviewed')] += 1
        by_category = collections.Counter(s['category'] for s in stories)
        sizes = collections.Counter('1' if s['chapters'] == 1 else '2-3' if s['chapters'] <= 3 else '4-9' if s['chapters'] <= 9
                                    else '10-29' if s['chapters'] <= 29 else '30+' for s in stories)
        readable = [r['id'] for r in self.records if self.readable(r['id'])]
        coverage = {'model': 4, 'records': len(self.records), 'readableDocs': len(readable),
                    'assignedDocs': sum(1 for r in readable if r in mapping),
                    'unassignedDocs': sorted(r for r in readable if r not in mapping)[:50],
                    'sharedDocs': sum(1 for v in self.appearances.values() if len(v) > 1),
                    'stories': len(stories), 'byCategory': dict(by_category), 'sizes': dict(sizes), 'hubs': len(self.hubs),
                    'review': {k: dict(v) for k, v in review.items()}, 'orphanFragments': orphans, 'warnings': self.warnings,
                    'report': dict(self.report)}
        dump(ROOT / 'public/data/story-coverage.json', coverage)
        print(json.dumps(coverage, ensure_ascii=False, indent=1))


