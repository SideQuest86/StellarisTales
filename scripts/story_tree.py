    def families_membership(self):
        member_of = {}
        self.family_conf = {}
        for f in self.families:
            self.family_conf[f['id']] = f
            for r in self.records:
                if (r['id'] in f.get('members', []) or any(r['source'].endswith(s) for s in f.get('sources', []))
                        or any(r['id'].startswith(p) for p in f.get('prefixes', []))
                        or any(r['eventId'].split('.')[0] == ran['namespace'] and (not ran.get('source') or r['source'].endswith(ran['source']))
                               and r['eventId'].split('.')[-1].isdigit() and ran['min'] <= int(r['eventId'].split('.')[-1]) <= ran['max']
                               for ran in f.get('ranges', []))):
                    member_of.setdefault(r['id'], f['id'])
        for sid, fragment in self.fragments.items():
            for rid in fragment.get('include', []):
                if rid not in self.byid:
                    raise ValueError(f'{sid}: included record no longer exists: {rid}')
                member_of[rid] = sid
            for rid in fragment.get('exclude', []):
                if member_of.get(rid) == sid:
                    del member_of[rid]
                self.excluded[sid].add(rid)  # also keeps a reachable non-member out of this story's tree
        self.member_of = member_of

    def find_roots(self):
        """Root components: strongly connected components of the narrative graph with no outside caller."""
        adj = collections.defaultdict(set)
        for src, calls in self.out.items():
            rules = self.suppressed.get(src, [])
            for c in calls:
                option = next((p.get('key') for p in c['path'] if p['k'] == 'option'), None)
                if any(s['to'] == c['to'] and s.get('option') in (None, option) for s in rules):
                    continue  # reviewed false continuation
                if c['to'] not in self.hubs:  # a hub's own outcomes belong to the hub's story
                    adj[src].add(c['to'])
        for src, edges in self.extra_edges.items():
            for target, info in edges:
                if not info.get('external'):
                    adj[src].add(target)
        nodes = [r['id'] for r in self.records]
        comp = strongly_connected(nodes, adj)
        external = set()
        for src, targets in adj.items():
            for t in targets:
                if comp[src] != comp[t]:
                    external.add(comp[t])
        members = collections.defaultdict(list)
        for rid in nodes:
            members[comp[rid]].append(rid)
        roots = []
        for c, rids in members.items():
            if c in external:
                continue
            free = [r for r in rids if r not in self.member_of]
            if not free or not any(self.readable(r) or self.composite(r) for r in free):
                continue
            entries = sorted(free, key=lambda r: (not self.triggers.get(r), not self.readable(r), self.order[r]))
            roots.append(entries)
        # Hubs are stories of their own (unless a curated family owns them).
        for hub in sorted(self.hubs):
            if hub not in self.member_of and (self.readable(hub) or self.composite(hub)) and not any(hub in e for e in roots):
                roots.append([hub])
        # A root whose every readable outcome belongs to one curated family is that family's entry
        # (e.g. the precursor anomaly categories that open a precursor investigation).
        kept = []
        for entries in roots:
            targets = {t for rid in entries for t, _ in self.composite(rid) if t not in self.hubs and t not in entries}
            owners = {self.member_of.get(t) for t in targets}
            if targets and len(owners) == 1 and None not in owners:
                family = owners.pop()
                for rid in entries:
                    self.member_of[rid] = family
                self.report['absorbed_into_family'] += 1
                continue
            kept.append(entries)
        # Roots fired only by the same game container (a contract, operation, megastructure, first-contact stage,
        # relic, resolution...) form one story; generic on_actions never group unrelated events.
        by_container = collections.defaultdict(list)
        final = []
        for entries in kept:
            containers = {c['from'] for rid in entries for c in self.triggers.get(rid, [])}
            single = next(iter(containers)) if len(containers) == 1 else None
            if single and ':' in single and not single.startswith(('on_actions:', 'scripted_effects:')):
                by_container[single].append(entries)
            else:
                final.append(entries)
        for container, groups in by_container.items():
            merged = [rid for entries in groups for rid in entries]
            final.append(merged)
            if len(groups) > 1:
                self.report['container_groups'] += 1
                self.container_of.update({rid: container for rid in merged})
        self.root_of = {}
        return final

